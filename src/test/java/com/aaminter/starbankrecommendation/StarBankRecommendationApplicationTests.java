
package com.aaminter.starbankrecommendation;

import com.aaminter.starbankrecommendation.model.recommendations.DynamicRule;
import com.aaminter.starbankrecommendation.repository.RecommendationRepository;
import com.aaminter.starbankrecommendation.repository.recommendations.DynamicRuleRepository;
import com.aaminter.starbankrecommendation.service.RuleStatsService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;

import javax.sql.DataSource;
import java.util.UUID;

import static org.springframework.http.MediaType.APPLICATION_JSON;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:recommendation_integration;DB_CLOSE_DELAY=-1",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "spring.datasource.hikari.read-only=false",
        "spring.liquibase.enabled=false",
        "custom.datasource.recommendations.jdbc-url=jdbc:h2:mem:rec_dummy;DB_CLOSE_DELAY=-1",
        "custom.datasource.recommendations.driver-class-name=org.h2.Driver",
        "custom.datasource.recommendations.username=sa",
        "custom.datasource.recommendations.password="
})
@AutoConfigureMockMvc
class StarBankRecommendationApplicationTests {

    private static final UUID INVEST_500_ID =
            UUID.fromString("147f6a0f-3b91-413b-ab99-87f081d60d5a");

    private static final UUID USER_ID =
            UUID.fromString("cd515076-5d8a-44be-930e-8d4fcb79f42d");

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private RecommendationRepository recommendationRepository;

    @Autowired
    private DynamicRuleRepository dynamicRuleRepository;

    @Autowired
    @Qualifier("recommendationsDataSource")
    private DataSource recommendationsDataSource;

    @MockitoBean
    private RuleStatsService ruleStatsService;

    private UUID debitProductId;
    private UUID savingProductId;

    @BeforeEach
    void setUp() {
        JdbcTemplate recommendationsJdbcTemplate =
                new JdbcTemplate(recommendationsDataSource);

        recommendationsJdbcTemplate.execute(
                "DROP TABLE IF EXISTS DYNAMIC_RULES"
        );

        recommendationsJdbcTemplate.execute("""
                CREATE TABLE DYNAMIC_RULES (
                    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    PRODUCT_ID UUID NOT NULL,
                    PRODUCT_NAME VARCHAR(255) NOT NULL,
                    PRODUCT_TEXT TEXT NOT NULL,
                    RULE JSON NOT NULL
                )
                """);

        jdbcTemplate.execute("DROP TABLE IF EXISTS TRANSACTIONS");
        jdbcTemplate.execute("DROP TABLE IF EXISTS PRODUCTS");

        jdbcTemplate.execute("""
                CREATE TABLE PRODUCTS (
                    ID UUID PRIMARY KEY,
                    TYPE VARCHAR(255) NOT NULL,
                    NAME VARCHAR(255) NOT NULL
                )
                """);

        jdbcTemplate.execute("""
                CREATE TABLE TRANSACTIONS (
                    ID UUID PRIMARY KEY,
                    PRODUCT_ID UUID NOT NULL,
                    USER_ID UUID NOT NULL,
                    TYPE VARCHAR(255) NOT NULL,
                    AMOUNT INTEGER NOT NULL
                )
                """);

        debitProductId = insertProduct("DEBIT", "Debit");
        savingProductId = insertProduct("SAVING", "Saving");

        // Очищаем кеш после подготовки новой тестовой БД.
        recommendationRepository.clearCache();
    }

    @Test
    void shouldClearCustomerMetricsCacheThroughManagementEndpoint()
            throws Exception {

        insertTransaction(debitProductId, USER_ID, "DEPOSIT", 1_000);

        var cached = recommendationRepository.getCustomerMetrics(USER_ID);
        assertEquals(
                1_000,
                cached.forProduct(com.aaminter.starbankrecommendation.model.ProductType.DEBIT)
                        .depositSum().longValue()
        );

        insertTransaction(debitProductId, USER_ID, "DEPOSIT", 5_000);

        mockMvc.perform(post("/management/clear-caches"))
                .andExpect(status().isNoContent());

        var refreshed = recommendationRepository.getCustomerMetrics(USER_ID);
        assertEquals(
                6_000,
                refreshed.forProduct(com.aaminter.starbankrecommendation.model.ProductType.DEBIT)
                        .depositSum().longValue()
        );
    }

    @Test
    void shouldReturnInvest500RecommendationThroughHttpApi()
            throws Exception {

        insertTransaction(debitProductId, USER_ID, "DEPOSIT", 1_000);
        insertTransaction(savingProductId, USER_ID, "DEPOSIT", 1_200);

        mockMvc.perform(get("/recommendation/{user_id}", USER_ID))
                .andExpect(status().isOk())
                .andExpect(content().contentTypeCompatibleWith(APPLICATION_JSON))
                .andExpect(jsonPath("$.user_id").value(USER_ID.toString()))
                .andExpect(jsonPath("$.recommendations.length()").value(1))
                .andExpect(jsonPath("$.recommendations[0].name")
                        .value("Invest 500"))
                .andExpect(jsonPath("$.recommendations[0].id")
                        .value(INVEST_500_ID.toString()))
                .andExpect(jsonPath("$.recommendations[0].text").isNotEmpty());
    }

    @Test
    void shouldReturnEmptyRecommendationsThroughHttpApi()
            throws Exception {

        mockMvc.perform(get(
                        "/recommendation/{user_id}",
                        USER_ID
                ))
                .andExpect(status().isOk())
                .andExpect(content().contentTypeCompatibleWith(APPLICATION_JSON))
                .andExpect(jsonPath("$.user_id").value(USER_ID.toString()))
                .andExpect(jsonPath("$.recommendations").isArray())
                .andExpect(jsonPath("$.recommendations.length()").value(0));
    }

    @Test
    void shouldReturnDynamicRecommendationThroughHttpApi()
            throws Exception {

        UUID dynamicProductId =
                UUID.fromString("a47f6a0f-3b91-413b-ab99-87f081d60d5a");

        dynamicRuleRepository.save(new DynamicRule(
                dynamicProductId,
                "Dynamic Debit",
                "Dynamic debit recommendation",
                """
                [{"query":"USER_OF","arguments":["DEBIT"],"negate":false}]
                """
        ));

        insertTransaction(debitProductId, USER_ID, "DEPOSIT", 1_000);

        mockMvc.perform(get("/recommendation/{user_id}", USER_ID))
                .andExpect(status().isOk())
                .andExpect(content().contentTypeCompatibleWith(APPLICATION_JSON))
                .andExpect(jsonPath("$.user_id").value(USER_ID.toString()))
                .andExpect(jsonPath("$.recommendations.length()").value(1))
                .andExpect(jsonPath("$.recommendations[0].name")
                        .value("Dynamic Debit"))
                .andExpect(jsonPath("$.recommendations[0].id")
                        .value(dynamicProductId.toString()))
                .andExpect(jsonPath("$.recommendations[0].text")
                        .value("Dynamic debit recommendation"));
    }

    private UUID insertProduct(String type, String name) {
        UUID productId = UUID.randomUUID();

        jdbcTemplate.update(
                "INSERT INTO PRODUCTS (ID, TYPE, NAME) VALUES (?, ?, ?)",
                productId,
                type,
                name
        );

        return productId;
    }

    private void insertTransaction(
            UUID productId,
            UUID userId,
            String type,
            int amount
    ) {
        jdbcTemplate.update(
                """
                INSERT INTO TRANSACTIONS (ID, PRODUCT_ID, USER_ID, TYPE, AMOUNT)
                VALUES (?, ?, ?, ?, ?)
                """,
                UUID.randomUUID(),
                productId,
                userId,
                type,
                amount
        );
    }
}
